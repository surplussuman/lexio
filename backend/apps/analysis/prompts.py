"""Prompt construction for the AI analysis pipeline (LLD §6.3).

Scoring + annotation + feedback narrative are combined into ONE call, per the
§17.3 cost-management rule, so `build_scoring_prompt` asks for all three in a
single JSON response.

One deliberate change from §6.3: annotations ask the model for the exact
`text` it is flagging rather than character offsets. Models are unreliable at
counting characters; offsets are computed locally in services.py with
str.find(). The stored annotation still carries span_start/span_end as §6.4
specifies.
"""
from .rubrics import DIMENSIONS

SCORING_SYSTEM = (
    "You are Echo, an expert communication coach and assessor for college students. "
    "You assess a student's spoken or written response against a rubric and return ONLY "
    "a JSON object — no markdown, no prose, no preamble. Be specific and concrete: quote "
    "the student's own words rather than giving generic advice. Be encouraging but honest."
)

ANNOTATION_TYPES = "filler | grammar | hedge | strong | structure_gap"


def build_scoring_prompt(
    *,
    mode: str,
    prompt_text: str,
    response_text: str,
    weights: dict,
    audio: dict | None,
    timing_note: str = "",
    delivery_note: str = "",
) -> str:
    dimension_lines = "\n".join(f"- {d}: {DIMENSIONS[d]} (weight {w}%)" for d, w in weights.items())
    audio_line = ""
    if audio:
        audio_line = (
            f"\nAudio features measured from the recording: {audio['wpm']} words/min, "
            f"{audio['filler_count']} filler words ({audio['filler_ratio']}% of words), "
            f"{audio['pause_count']} pauses over 800ms, duration {audio['duration_seconds']}s."
        )
    if timing_note:
        audio_line += (
            f"\n\nTIME USED — this matters and must be reflected in the scores and named in the "
            f"narrative: {timing_note}"
        )
    if delivery_note:
        audio_line += f"\n\n{delivery_note}"

    return f"""Mode: {mode}
Task the student was given: {prompt_text}

Rubric dimensions to score (0-100 each):
{dimension_lines}
{audio_line}

Student's response:
\"\"\"
{response_text}
\"\"\"

Return JSON with exactly this shape:
{{
  "dimensions": [
    {{"id": "<one of: {", ".join(weights)}>", "score": 0-100,
      "rationale": "one sentence citing something specific they said",
      "key_issues": ["short phrase", ...],
      "strong_moments": ["short phrase", ...]}}
  ],
  "annotations": [
    {{"text": "<exact substring copied verbatim from the response>",
      "type": "{ANNOTATION_TYPES}",
      "message": "what to fix or why this worked, max 18 words"}}
  ],
  "authenticity": {{
    "ai_likelihood": 0-100,
    "signals": ["short phrase naming what suggests it, max 12 words", ...]
  }},
  "narrative": "2-3 short paragraphs, second person, addressed to the student. Name one concrete thing that worked and one specific thing to change next time."
}}

Score every dimension listed above and no others. Give 3-6 annotations, including at least one 'strong'.

For "authenticity", judge only how likely it is that this response was generated by an AI
rather than produced by the student themselves. Evidence of AI generation: uniformly polished
sentences with no self-correction, textbook transitions ("Furthermore", "In conclusion"), an
essay register in something that was spoken aloud, zero fillers or hesitation in a long
unscripted answer, or a suspiciously balanced this-versus-that structure. Evidence AGAINST:
hesitation, restarts, informal phrasing, personal or local detail, uneven quality. A capable
student writing carefully is NOT evidence of AI — be conservative, and return a low number
when you are unsure. This never affects their score."""


NARRATIVE_SYSTEM = (
    "You are Echo, an encouraging but honest communication coach for college students. "
    "You write short, specific feedback in the second person. No markdown, no lists, no preamble."
)


def build_objective_narrative_prompt(*, mode: str, percentage: int, breakdown: list[dict]) -> str:
    """Objective modes are scored deterministically; the AI is only asked for
    Echo's narrative, which keeps this call small and cheap (§17.3)."""
    missed = [b for b in breakdown if not b["is_correct"]][:6]
    missed_lines = "\n".join(f"- {m['question']} (they chose option {m['given']}, correct was {m['answer']})" for m in missed) or "- none"
    return f"""A student scored {percentage}% on a {mode} assessment ({len(breakdown)} questions).

Questions they got wrong:
{missed_lines}

Write 2 short paragraphs of feedback: what the pattern in their mistakes suggests, and the single most useful thing to practise next. Max 110 words total."""
